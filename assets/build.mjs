import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const assetsDirectory = dirname(fileURLToPath(import.meta.url));
const sourceDirectory = join(assetsDirectory, 'src', 'controllers');
const distDirectory = join(assetsDirectory, 'dist');
const outputDirectory = join(distDirectory, 'controllers');

// Keep all runtime libraries external. They are declared as peer dependencies
// and must be supplied by the host application's asset pipeline.
const external = [
    '@hotwired/stimulus',
    '@hotwired/turbo',
    '@symfony/ux-live-component',
    'bootstrap',
    'ckeditor5',
    'debounce',
    'sortablejs',
    'tom-select',
    'vanillajs-datepicker',
];

const esbuildModule = process.env.LEXIO_ADMIN_ESBUILD
    ? pathToFileURL(join(process.env.LEXIO_ADMIN_ESBUILD, 'lib', 'main.js')).href
    : 'esbuild';
const { build } = await import(esbuildModule);
const packageJson = JSON.parse(await readFile(join(assetsDirectory, 'package.json'), 'utf8'));
const controllerFiles = (await readdir(sourceDirectory))
    .filter((file) => file.endsWith('_controller.js'))
    .sort();

const quote = (value) => JSON.stringify(value);
const controllerImport = (main) => {
    if (!main.startsWith('dist/')) {
        throw new Error(`Controller entry "${main}" must be inside dist/.`);
    }

    return `./${main.slice('dist/'.length)}`;
};
const enabledAutoimports = (metadata) => Object.entries(metadata.autoimport ?? {})
    .filter(([, enabled]) => enabled)
    .map(([specifier]) => specifier);
const generateRegistrar = (controllers) => {
    const imports = [`import { registerControllers } from './controller_registrar.js';`];
    const eagerAutoimports = new Set();
    const eagerControllers = [];
    const lazyControllers = [];
    let eagerIndex = 0;

    for (const [identifier, metadata] of Object.entries(controllers).sort(([left], [right]) => left.localeCompare(right))) {
        if (metadata.enabled === false) {
            continue;
        }

        const main = controllerImport(metadata.main);
        const autoimports = enabledAutoimports(metadata);

        if (metadata.fetch === 'lazy') {
            const dynamicImports = [main, ...autoimports].map((specifier) => `import(${quote(specifier)})`);
            const loadController = dynamicImports.length === 1
                ? `${dynamicImports[0]}.then((module) => module.default)`
                : `Promise.all([${dynamicImports.join(', ')}]).then(([module]) => module.default)`;

            lazyControllers.push(`    ${quote(identifier)}: () => ${loadController},`);

            continue;
        }

        const variable = `controller_${eagerIndex++}`;
        imports.push(`import ${variable} from ${quote(main)};`);
        autoimports.forEach((specifier) => eagerAutoimports.add(specifier));
        eagerControllers.push(`    ${quote(identifier)}: ${variable},`);
    }

    eagerAutoimports.forEach((specifier) => imports.push(`import ${quote(specifier)};`));

    return `${[
        '// This file is generated by build.mjs. Do not edit it manually.',
        ...imports,
        '',
        'const eagerControllers = {',
        ...eagerControllers,
        '};',
        '',
        'const lazyControllers = {',
        ...lazyControllers,
        '};',
        '',
        'export function registerLexioAdminControllers(application) {',
        '    return registerControllers(application, eagerControllers, lazyControllers);',
        '}',
        '',
    ].join('\n')}\n`;
};

await mkdir(distDirectory, {recursive: true});

await build({
    bundle: true,
    entryPoints: [join(assetsDirectory, 'src', 'bootstrap.js')],
    external,
    format: 'esm',
    minify: false,
    outfile: join(distDirectory, 'bootstrap.js'),
    platform: 'browser',
    sourcemap: false,
    target: ['es2020'],
});

await build({
    bundle: true,
    entryPoints: [join(assetsDirectory, 'src', 'controller_registrar.js')],
    format: 'esm',
    minify: false,
    outfile: join(distDirectory, 'controller_registrar.js'),
    platform: 'browser',
    sourcemap: false,
    target: ['es2020'],
});

await Promise.all(controllerFiles.map((file) => build({
    bundle: true,
    entryPoints: [join(sourceDirectory, file)],
    external,
    format: 'esm',
    loader: {
        '.css': 'empty',
        '.scss': 'empty',
    },
    minify: false,
    outfile: join(outputDirectory, file),
    platform: 'browser',
    sourcemap: false,
    target: ['es2020'],
})));

await writeFile(
    join(distDirectory, 'register_controllers.js'),
    generateRegistrar(packageJson.symfony.controllers),
    'utf8',
);
